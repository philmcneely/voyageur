    expect(page.get_by_test_id("done-phone")).to_have_text("+1 555 010 4477")
    expect(page.get_by_test_id("done-age")).to_have_text("34")
    expect(page.get_by_test_id("done-birthdate")).to_have_text("1990-05-17")
    expect(page.get_by_test_id("done-delivery")).to_have_text("2026-12-15")
    expect(page.get_by_test_id("done-country")).to_have_text("US")
    expect(page.get_by_test_id("done-city")).to_have_text("Austin")
    expect(page.get_by_test_id("done-shipping")).to_have_text("express")
    expect(page.get_by_test_id("done-digest")).to_have_text("yes")
