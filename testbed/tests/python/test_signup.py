    page.locator("input[name=confirm]").fill("S3cretPass!")
    page.get_by_role("button", name="Next").click()
    page.get_by_label("Phone").fill("+1 555 010 4477")
    page.get_by_role("spinbutton", name="Age").fill("34")
    page.get_by_label("Birth date").fill("1990-05-17")
    page.get_by_role("button", name="Choose delivery date").click()
    page.get_by_test_id("calendar").get_by_role("button", name="15", exact=True).click()
    page.locator("select[name=country]").select_option("US")
    page.get_by_role("combobox", name="City").fill("Aus")
    page.get_by_role("option", name="Austin").click()
    page.get_by_role("radio", name="Express").check()
    page.get_by_placeholder("Gate code, drop-off instructions").fill("Leave with the concierge")
    page.get_by_text("Next", exact=True).click()
    page.get_by_role("switch", name="Weekly digest").click()
    page.get_by_role("tab", name="Billing contact").click()
    page.get_by_label("Billing email").fill("billing@example.com")
    page.get_by_label("Music").check()
    page.get_by_label("Travel").check()
    page.get_by_role("checkbox", name="Marketing emails").check()
