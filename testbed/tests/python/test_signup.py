def test_tabs_and_accordion(page: Page):
    page.set_default_timeout(TIMEOUT)
    page.goto(BASE + "step3.html")
    page.get_by_role("tab", name="Billing contact").click()
    page.get_by_label("Billing email").fill("ap@example.com")
    expect(page.get_by_test_id("live-summary")).to_contain_text("billing_email: ap@example.com")
    page.get_by_role("tab", name="Privacy").click()
    page.get_by_label("Show my profile publicly").check()
    expect(page.get_by_test_id("live-summary")).to_contain_text("public: yes")
    page.get_by_text("Advanced options").click()
    page.get_by_label("Referral code").fill("PROMO7")
    expect(page.get_by_test_id("live-summary")).to_contain_text("referral: PROMO7")


def test_plan_table_and_stepper(page: Page):
    page.set_default_timeout(TIMEOUT)
    page.goto(BASE + "step3.html")
    page.get_by_role("button", name="Select").nth(1).click()
    expect(page.get_by_test_id("live-summary")).to_contain_text("plan: pro")
    page.get_by_role("row", name="Team").get_by_role("button", name="Select").click()
    expect(page.get_by_test_id("live-summary")).to_contain_text("plan: team")
    page.get_by_role("button", name="Increase seats").click()
    page.get_by_role("button", name="Increase seats").click()
    page.get_by_role("button", name="Increase seats").click()
    page.get_by_role("button", name="Decrease seats").click()
    expect(page.get_by_test_id("live-summary")).to_contain_text("seats: 3")
